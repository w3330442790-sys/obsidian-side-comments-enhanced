import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFile } from "node:fs/promises";
import { dirname } from "node:path";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";

const prod = (process.argv[2] === "production");

/**
 * Taube Markdown Tool is GPL-3.0-only and fuses MIT-licensed mind-map sources
 * (Weilanx, gogoga) plus bundled runtime dependencies. The released main.js is a
 * generated bundle, so keep every applicable notice in a preserved banner.
 */
function licenseBanner() {
	const notices = [
		"Copyright (c) 2026 taube; original Side-Comments-origin and upstream notices retained.",
		...[
			"LICENSE",
			"vendor/personal-mindmap/LICENSE",
			"vendor/personal-mindmap/vendor/gogoga/LICENSE",
			"vendor/personal-mindmap/webview/LICENSE-OFL.txt",
		].map(file => readFileSync(file, "utf8")),
	];
	const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
	for (const [directory, entry] of Object.entries(lock.packages)) {
		if (!directory || entry.dev || !directory.startsWith("node_modules/") || !existsSync(directory)) continue;
		for (const name of readdirSync(directory).filter(file => /^(licen[cs]e|copying)(\.|$)/i.test(file))) {
			const file = `${directory}/${name}`;
			if (statSync(file).isFile()) {
				notices.push(directory.replace(/^node_modules\//, ""), readFileSync(file, "utf8"));
			}
		}
	}
	return "/*!\n" + notices.join("\n\n").replace(/\*\//g, "* /") + "\n*/\n" +
		`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;
}

/**
 * docx 8.5.0 bundles two legacy IE scheduling fallbacks from JSZip. They create
 * temporary script elements and accept string callbacks through new Function().
 * Obsidian has native timers and MessageChannel, so those unreachable fallbacks
 * are removed while bundling. Exact match counts make dependency changes fail
 * the build instead of silently shipping unreviewed compatibility code.
 */
const safeDocxCompatibilityPlugin = {
	name: "safe-docx-compatibility",
	setup(build) {
		build.onLoad({ filter: /node_modules[\\/]docx[\\/](?:build|dist)[\\/]index\.mjs$/ }, async (args) => {
			let contents = await readFile(args.path, "utf8");
			const replacements = [
				{
					name: "Promise scheduler script fallback",
					pattern: /"document" in ([\w$]+) && "onreadystatechange" in \1\.document\.createElement\("script"\)/g,
					replacement: "false",
				},
				{
					name: "setImmediate script fallback",
					pattern: /([\w$]+) && "onreadystatechange" in \1\.createElement\("script"\)/g,
					replacement: "false",
				},
				{
					name: "setImmediate string callback",
					pattern: /"function" != typeof ([\w$]+) && \(\1 = new Function\("" \+ \1\)\)/g,
					replacement: '"function" != typeof $1 && (() => { throw new TypeError("setImmediate callback must be a function"); })()',
				},
			];

			for (const replacement of replacements) {
				const matches = contents.match(replacement.pattern)?.length ?? 0;
				if (matches !== 1) {
					throw new Error(`${replacement.name}: expected one match in ${args.path}, found ${matches}`);
				}
				contents = contents.replace(replacement.pattern, replacement.replacement);
			}

			return { contents, loader: "js", resolveDir: dirname(args.path) };
		});
	},
};

/**
 * React DOM 19 contains dead resource-hoisting branches that would create a
 * <script> element if the app rendered a script resource. This plugin never
 * renders one; rename the element so the bundle security check can keep proving
 * that no dynamic script can be created, while the unreachable branch stays
 * harmless if a future extension ever reached it.
 */
const neutraliseReactScriptResourcesPlugin = {
	name: "neutralise-react-script-resources",
	setup(build) {
		build.onLoad({ filter: /react-dom[\\/]cjs[\\/]react-dom-client\.production\.js$/ }, async (args) => {
			let contents = await readFile(args.path, "utf8");
			const matches = contents.match(/createElement\("script"\)/g)?.length ?? 0;
			if (matches !== 3) {
				throw new Error(`React DOM script resource branch changed: expected 3 matches in ${args.path}, found ${matches}`);
			}
			contents = contents.replace(/createElement\("script"\)/g, 'createElement("script-disabled")');
			return { contents, loader: "js", resolveDir: dirname(args.path) };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: licenseBanner(),
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((moduleName) => `node:${moduleName}`)],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	jsx: "automatic",
	loader: {
		".css": "empty",
		".woff2": "dataurl",
	},
	define: {
		"process.env.NODE_ENV": JSON.stringify(prod ? "production" : "development"),
	},
	plugins: [safeDocxCompatibilityPlugin, neutraliseReactScriptResourcesPlugin],
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
